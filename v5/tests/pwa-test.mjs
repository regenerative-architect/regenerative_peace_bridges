import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const source=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
let checks=0;
function environment(failInstall=false){
 const buckets=new Map(),handlers={},scope='https://example.test/app/';
 const key=x=>typeof x==='string'?x:x.url||x.href;
 const caches={keys:async()=>[...buckets.keys()],delete:async n=>buckets.delete(n),open:async n=>{if(!buckets.has(n))buckets.set(n,new Map());const map=buckets.get(n);return {addAll:async reqs=>{if(failInstall)throw Error('Quota exceeded');for(const r of reqs)map.set(key(r),new Response('release '+n));},put:async(k,v)=>map.set(key(k),v),match:async k=>map.get(key(k))?.clone()};}};
 const self={registration:{scope},location:{origin:'https://example.test'},clients:{claim:async()=>{},matchAll:async()=>[{url:scope}]},skipWaiting:async()=>{},addEventListener:(n,fn)=>handlers[n]=fn};
 vm.runInNewContext(source,{self,caches,URL,Request,Response});
 const run=async name=>{let pending;handlers[name]({waitUntil:p=>pending=p});await pending;};
 const status=async()=>{let result,pending;handlers.message({data:{type:'ARCHIVE_STATUS'},ports:[{postMessage:x=>result=x}],waitUntil:p=>pending=p});await pending;return result;};
 const fetch=async path=>{let pending;handlers.fetch({request:{url:new URL(path,scope).href,method:'GET',mode:'navigate'},respondWith:p=>pending=p});return pending;};
 const remove=async version=>{let result,pending;handlers.message({data:{type:'REMOVE_ARCHIVE',version},ports:[{postMessage:x=>result=x}],waitUntil:p=>pending=p});await pending;return result;};
 return {buckets,caches,run,status,fetch,scope,remove,self};
}
const e=environment();await e.run('install');const initial=await e.status();assert(initial.complete);checks++;
assert((await e.fetch('index.html')).status===200);checks++;
assert.equal(await e.fetch('../outside'),undefined);checks++;
assert.equal(await e.fetch('unrelated.html'),undefined);checks++;
await e.caches.open('rpb-core-v-old');await e.run('activate');assert(e.buckets.has('rpb-core-v-old'));checks++;
const active=e.buckets.get(initial.version),index=new URL('index.html',e.scope).href;active.delete(index);
assert(!(await e.status()).complete);checks++;
assert.equal((await e.fetch('index.html')).status,503);checks++;
assert((await (await e.fetch('index.html')).text()).includes('plans have not been deleted'));checks++;
const old=await e.caches.open('rpb-core-v-old');await old.put(index,new Response('pinned old release'));
await old.put(new URL('__release-manifest',e.scope),new Response(JSON.stringify({files:['./index.html']})));
const settings=await e.caches.open('rpb-release-settings');await settings.put(new URL('__release-pin',e.scope),new Response(JSON.stringify({version:'rpb-core-v-old'})));
assert.equal((await e.status()).version,'rpb-core-v-old');checks++;
assert((await e.status()).complete);checks++;
assert.equal(await (await e.fetch('index.html')).text(),'pinned old release');checks++;
await e.run('activate');assert.equal((await e.status()).version,'rpb-core-v-old');checks++;
const broken=environment(true);await broken.caches.open('rpb-core-v-previous');await assert.rejects(broken.run('install'),/Quota/);checks++;
assert.deepEqual([...broken.buckets.keys()],['rpb-core-v-previous']);checks++;
assert((await e.remove(initial.version)).error.includes('current'));checks++;
assert((await e.remove('rpb-core-v-old')).error.includes('pinned'));checks++;
assert((await e.remove('unrelated-cache')).error);checks++;
await e.caches.open('rpb-core-v-disposable');e.self.registration.waiting={};
assert((await e.remove('rpb-core-v-disposable')).error.includes('pending'));checks++;
e.self.registration.waiting=null;e.self.clients.matchAll=async()=>[{url:e.scope},{url:e.scope+'index.html'}];
assert((await e.remove('rpb-core-v-disposable')).error.includes('other app tabs'));checks++;
e.self.clients.matchAll=async()=>[{url:e.scope}];assert((await e.remove('rpb-core-v-disposable')).removed);checks++;
assert(!e.buckets.has('rpb-core-v-disposable'));checks++;
await e.caches.delete('rpb-core-v-old');assert.equal((await e.status()).version,'rpb-core-v-old');checks++;
assert(!(await e.status()).complete);checks++;
assert.equal((await e.fetch('index.html')).status,503);checks++;
console.log(`Passed ${checks} PWA worker checks.`);
