import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const box={window:{}};
for(const f of ['data.js','impact.js','knowledge.js','systems.js'])vm.runInNewContext(readFileSync(new URL('../'+f,import.meta.url),'utf8'),box);
const S=box.window.RPB_SYSTEMS,K=box.window.RPB_KNOWLEDGE,at='2026-10-23T12:00:00.000Z';
let checks=0;const check=f=>{f();checks++;};
check(()=>assert.equal(Object.keys(S.clean(undefined).maps).length,0));
for(const type of ['water','food','education','health','land','governance','women','youth','restoration'])check(()=>assert.ok(S.types[type]));
for(const t of S.templates){const g=S.graph(S.template(t.id));check(()=>assert.ok(g.nodes.length&&g.edges.length));check(()=>assert.ok(g.edges.every(e=>e.status==='hypothesis')));check(()=>assert.equal(g.sharing,'local'));}
const chain=S.template('water-school'),cycle=S.template('restoration-food');
check(()=>assert.equal(S.path(chain,'n0','n3').length,4));
check(()=>assert.equal(S.path(chain,'n3','n0').length,0));
check(()=>assert.equal(S.path(chain,'missing','missing').length,0));
check(()=>assert.equal(S.loopEdges(chain).length,0));
check(()=>assert.equal(S.loopEdges(cycle).length,4));
let raw=S.save(S.empty(),'water',chain,'Initial draft',at);
check(()=>assert.equal(S.get(raw,'water').history.length,1));
check(()=>assert.equal(S.get(raw,'school').nodes.length,0));
check(()=>assert.equal(S.lines(raw,'water').length,0));
check(()=>assert.ok(S.lines(raw,'water',false).join(' ').includes('School Attendance')));
check(()=>assert.throws(()=>S.packet(raw,'water',K.empty())));
const bad=[g=>g.nodes.push(g.nodes[0]),g=>g.nodes[0].type='invalid',g=>g.nodes[0].label='',g=>g.nodes[0].metricId='invalid',g=>g.nodes[0].label='x'.repeat(101),g=>g.edges[0].to='missing',g=>g.edges[0].to=g.edges[0].from,g=>g.edges.push(g.edges[0]),g=>g.edges[0].polarity='invalid',g=>g.edges[0].status='invalid',g=>g.edges[0].mechanism='',g=>g.edges[0].context='',g=>g.edges[0].status='observed',g=>g.edges[0].status='disputed',g=>g.edges[0].docId='invalid',g=>g.edges[0].knowledgeId='<img>',g=>g.sharing='shared',g=>g.sharing='unknown',g=>g.nodes=Array(31).fill(g.nodes[0]),g=>g.edges=Array(61).fill(g.edges[0])];
for(const mutate of bad){const g=S.template('water-school');mutate(g);check(()=>assert.throws(()=>S.graph(g)));}
check(()=>assert.throws(()=>S.save(raw,'missing',chain,'Bad bridge',at)));
check(()=>assert.throws(()=>S.save(raw,'water',chain,'',at)));
check(()=>assert.throws(()=>S.save(raw,'water',chain,'Bad date','not a date')));
check(()=>assert.throws(()=>S.save(raw,'water',chain,'Earlier date','2020-01-01T00:00:00.000Z')));
const shared=S.template('water-school');shared.sharing='shared';shared.permission='Community workshop approved this map.';shared.edges[0].knowledgeId='local-account';
raw=S.save(raw,'water',shared,'Approved sharing',at);
check(()=>assert.ok(S.lines(raw,'water').join(' ').includes('Sharing agreement')));
const packet=S.packet(raw,'water',K.empty());
check(()=>assert.equal(packet.graph.edges[0].knowledgeId,''));
check(()=>assert.equal(S.get(raw,'water').edges[0].knowledgeId,'local-account'));
check(()=>assert.equal(packet.graph.history,undefined));
check(()=>assert.equal(S.readPacket(packet).sharing,'local'));
check(()=>assert.equal(S.readPacket(packet).permission,''));
check(()=>assert.throws(()=>S.readPacket({...packet,schema:2})));
check(()=>assert.throws(()=>S.readPacket({...packet,bridgeId:'invalid'})));
check(()=>assert.equal(JSON.stringify(S.clean(JSON.parse(JSON.stringify(raw)))),JSON.stringify(raw)));
check(()=>assert.ok(S.texts(raw).join(' ').includes('Initial draft')));
for(let i=0;i<25;i++)raw=S.save(raw,'water',chain,'Change '+i,at);
check(()=>assert.equal(S.get(raw,'water').history.length,20));
check(()=>assert.equal(S.get(raw,'water').history[0].reason,'Change 5'));
check(()=>assert.equal(chain.history,undefined));
const supported=S.template('water-school');supported.edges[0].status='observed';supported.edges[0].evidence='Voluntary group discussion, with absent perspectives noted.';
check(()=>assert.equal(S.graph(supported).edges[0].status,'observed'));
console.log(`Passed ${checks} peace systems model checks.`);
