#!/usr/bin/env node
/* =====================================================================
   tools/i18n-extract.mjs — builds lang/catalog.js: the list of every
   interface sentence that a language pack can translate.

   It reads:
     app.js      calls to t, tx, tr, trx and tn whose first argument is a
                 "double-quoted" English string (never a template string)
     index.html  elements marked data-i18n (interface words) or
                 data-i18n="reviewed" (safety, legal and guidance text),
                 and the attributes named in data-i18n-attr

   Run it after changing any interface text (Node.js 18 or newer):
       node tools/i18n-extract.mjs
   Use --check to report whether lang/catalog.js is up to date without
   changing it (the tests do this).
   ===================================================================== */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const app = read("app.js");
const html = read("index.html");

const ui = new Set();
const reviewed = new Set();
const plurals = new Map();
const problems = [];
const key = (s) => s.replace(/\s+/g, " ").trim();
// Our strings only use JSON-compatible escapes (\" \\ \n), so JSON can read them.
const unjs = (s) => JSON.parse('"' + s + '"');
const STR = String.raw`"((?:[^"\\]|\\.)*)"`;

// ----- app.js -----
for (const m of app.matchAll(new RegExp(String.raw`\b(tx|trx|tr|t)\(\s*` + STR, "g"))) {
  const k = key(unjs(m[2]));
  if (!k) continue;
  (m[1].startsWith("tr") ? reviewed : ui).add(k);
}
for (const m of app.matchAll(new RegExp(String.raw`\btn\(\s*` + STR + String.raw`\s*,\s*` + STR, "g"))) {
  const one = key(unjs(m[1]));
  const other = key(unjs(m[2]));
  ui.add(one);
  ui.add(other);
  plurals.set(other, one);
}
// Template strings can't be extracted, so they must not be passed in.
for (const m of app.matchAll(/\b(tx|trx|tr|t|tn)\(\s*`/g)) problems.push(`app.js: ${m[1]}() is called with a template string; use "{name}" placeholders instead`);

// ----- index.html -----
const ent = (s) => s.replace(/&nbsp;/g, " ").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");
const startTag = /<([a-z][a-z0-9]*)\b([^>]*)>/g;
let m;
while ((m = startTag.exec(html))) {
  const [whole, tag, attrs] = m;
  const mark = attrs.match(/\sdata-i18n(?:="([^"]*)")?(?=[\s/]|$)/);
  if (mark) {
    if (mark[1] !== undefined && mark[1] !== "reviewed") problems.push(`index.html: data-i18n="${mark[1]}" should be empty or "reviewed"`);
    const after = html.slice(m.index + whole.length);
    const textEnd = after.indexOf("<");
    const text = after.slice(0, textEnd);
    if (!after.slice(textEnd).startsWith("</" + tag)) {
      problems.push(`index.html: <${tag}> marked data-i18n must contain only text (near “${key(ent(text)).slice(0, 40)}”)`);
    } else {
      const k = key(ent(text));
      if (k) (mark[1] === "reviewed" ? reviewed : ui).add(k);
      else problems.push(`index.html: <${tag}> marked data-i18n is empty`);
    }
  }
  const attrList = attrs.match(/\sdata-i18n-attr="([^"]*)"/);
  if (attrList) {
    for (const name of attrList[1].split(",").map((x) => x.trim()).filter(Boolean)) {
      const v = attrs.match(new RegExp(`\\s${name}="([^"]*)"`));
      if (!v || !key(ent(v[1]))) problems.push(`index.html: <${tag}> lists ${name} in data-i18n-attr but has no ${name} text`);
      else ui.add(key(ent(v[1])));
    }
  }
}

for (const k of ui) if (reviewed.has(k)) problems.push(`“${k.slice(0, 60)}” is used both as interface text and as reviewed-only text; pick one`);
if (problems.length) {
  console.error("✗ The interface text has problems:\n  - " + problems.join("\n  - "));
  process.exit(2);
}

const sortAll = (set) => [...set].sort();
const data = {
  ui: sortAll(ui),
  reviewed: sortAll(reviewed),
  plurals: [...plurals.entries()].map(([other, one]) => [one, other]).sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0))
};
const out = `/* =====================================================================
   lang/catalog.js — generated by tools/i18n-extract.mjs from app.js and
   index.html. Do not edit by hand: run  node tools/i18n-extract.mjs
     ui        interface words that any language pack may translate
     reviewed  safety, legal and guidance text, used only from packs
               marked "reviewed"
     plurals   [singular, plural] pairs; a pack may give the plural as an
               object with its language's forms (zero, one, two, few,
               many, other)
   ===================================================================== */
window.RPB_CATALOG = ${JSON.stringify(data, null, 1)};
`;

const file = join(root, "lang", "catalog.js");
const current = existsSync(file) ? readFileSync(file, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== out) { console.error("lang/catalog.js is out of date. Run: node tools/i18n-extract.mjs"); process.exit(1); }
  console.log(`lang/catalog.js is up to date (${data.ui.length} interface, ${data.reviewed.length} reviewed-only).`);
} else {
  writeFileSync(file, out);
  console.log(`Wrote lang/catalog.js: ${data.ui.length} interface strings, ${data.reviewed.length} reviewed-only, ${data.plurals.length} plural pairs.`);
}
